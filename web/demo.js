/**
 * dalteno.com/lab/docrecon — docrecon in your browser. Nothing is sent anywhere.
 * Edits are applied onto a copy of the loaded case (web/formmerge.js), so fields the form does not display are kept.
 */
import { reconcile, RULES, VERSION } from "/lab/docrecon/docrecon.js";
import { applyEdit, effectiveBundle, asLine, INV_COLS, PL_COLS, INV_HEAD, PL_HEAD, BL_HEAD } from "/lab/docrecon/formmerge.js";

const REPO = "https://github.com/dalteno/docrecon";
const $ = (s, r = document) => r.querySelector(s);
const esc = (s) => String(s ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
const T = (k) => (window.DaltenoI18n ? window.DaltenoI18n.t(k) : k);
const tt = (k, fallback) => { const v = T(k); return v === k ? fallback : v; };

let cases = [], current = null, bundle = null, options = {};

function field(doc, key, value) {
  return `<label><span>${esc(key)}</span><input data-doc="${doc}" data-key="${esc(key)}" value="${esc(value ?? "")}" spellcheck="false" dir="ltr"></label>`;
}
function table(doc, cols, lines) {
  const head = cols.map((c) => `<th>${esc(c)}</th>`).join("");
  const rows = (lines ?? []).map((raw, i) => { const ln = asLine(raw); return `<tr>${cols.map((c) => `<td><input data-doc="${doc}" data-line="${i}" data-key="${esc(c)}" value="${esc(ln[c] ?? "")}" spellcheck="false" dir="ltr"></td>`).join("")}<td><button type="button" class="x" data-del="${doc}:${i}" aria-label="${esc(tt("w_remove", "Remove line"))}">×</button></td></tr>`; }).join("");
  return `<table dir="ltr"><thead><tr>${head}<th></th></tr></thead><tbody>${rows}</tbody></table><button type="button" class="addline" data-add="${doc}">${esc(tt("w_addline", "+ line"))}</button>`;
}

function render() {
  const b = bundle;
  $("#doc-invoice").innerHTML = `<h4>${esc(tt("d_invoice", "Commercial invoice"))}</h4><div class="fields">${INV_HEAD.map((k) => field("invoice", k, b.invoice?.[k])).join("")}</div>${table("invoice", INV_COLS, Array.isArray(b.invoice?.lines) ? b.invoice.lines : [])}`;
  $("#doc-packing").innerHTML = `<h4>${esc(tt("d_packing", "Packing list"))}</h4><div class="fields">${PL_HEAD.map((k) => field("packingList", k, b.packingList?.[k])).join("")}</div>${table("packingList", PL_COLS, Array.isArray(b.packingList?.lines) ? b.packingList.lines : [])}`;
  $("#doc-bl").innerHTML = `<h4>${esc(tt("d_bl", "Bill of lading"))}</h4><div class="fields">${BL_HEAD.map((k) => field("billOfLading", k, b.billOfLading?.[k])).join("")}</div>`;
  const tb = $("#rulesbody"); if (tb) tb.innerHTML = RULES.map((r) => `<tr><td>${r.id}<br><small>${esc(r.code)}</small></td><td>${esc(r.contract)}<br><small>${r.severity}</small></td></tr>`).join("");
  run();
}

function run() {
  const b = effectiveBundle(bundle);
  const t0 = performance.now();
  const report = reconcile(b, options);
  const ms = performance.now() - t0;
  const badge = $("#status");
  badge.textContent = report.status;
  badge.className = "status " + report.status.toLowerCase();
  $("#meta").textContent = `${report.findings.length} ${report.findings.length === 1 ? tt("w_finding_one", "finding") : tt("w_finding_many", "findings")} · ${report.rulesEvaluated} ${tt("w_rules", "rules")} · ${ms.toFixed(2)} ms · ${tt("w_engine", "engine")} ${VERSION}`;
  const rows = report.findings.map((f) => `<tr class="${f.severity.toLowerCase()}">
    <td><a href="#rules" title="${esc(RULES.find((r) => r.id === f.rule)?.contract)}">${f.rule}</a><br><small>${esc(f.code)}</small></td>
    <td><span class="sev">${f.severity}</span></td>
    <td><code>${esc(f.field)}</code><br><small>${esc(f.documents.join(" · "))}</small></td>
    <td><small>${esc(tt("w_expected", "expected"))}</small> ${esc(f.expected)}<br><small>${esc(tt("w_found", "found"))}</small> ${esc(f.actual)}</td>
    <td lang="en" dir="ltr">${esc(f.reason)}</td></tr>`).join("");
  $("#findings").innerHTML = rows ? `<table><thead><tr><th>${esc(tt("w_h_rule", "rule"))}</th><th>${esc(tt("w_h_sev", "severity"))}</th><th>${esc(tt("w_h_field", "field"))}</th><th>${esc(tt("w_h_values", "values"))}</th><th>${esc(tt("w_h_why", "why"))}</th></tr></thead><tbody>${rows}</tbody></table>` : `<p class="ok">${esc(tt("w_ok", "No findings — the three documents agree under every rule."))}</p>`;
  $("#pin").innerHTML = current ? `<a href="${REPO}/blob/main/cases/${current.id}.json">cases/${current.id}.json</a> ${esc(tt("w_pins", "pins this case: expects"))} ${current.expect.length ? current.expect.map((e) => `<code>${esc(e)}</code>`).join(" ") : `<code>${esc(tt("w_none", "no findings"))}</code>`}` : "";
  $("#download").onclick = () => {
    const blob = new Blob([JSON.stringify({ note: "Synthetic data. Generated by docrecon in the browser; not a customs document.", input: b, options, report }, null, 2)], { type: "application/json" });
    const a = document.createElement("a"); a.href = URL.createObjectURL(blob); a.download = `docrecon-report-${current?.id ?? "custom"}.json`; a.click(); URL.revokeObjectURL(a.href);
  };
}

function loadCase(id) {
  current = cases.find((c) => c.id === id) ?? cases[0];
  bundle = structuredClone(current.bundle);
  options = current.options ?? {};
  $("#casetitle").textContent = current.title + (current.adversarial ? ` — ${tt("w_adversarial", "adversarial")}` : "");
  $("#options").textContent = Object.keys(options).length ? tt("w_options", "options:") + " " + JSON.stringify(options) : tt("w_defaults", "default options (qty ±0, weight ±2 %, amounts ±0.01, span ≤ 60 days)");
  render();
}

async function init() {
  const root = $("#demo");
  try { cases = await (await fetch("/lab/docrecon/cases.json", { cache: "no-cache" })).json(); }
  catch (e) { root.innerHTML = `<p class="err">Could not load the shared cases (${esc(e.message)}). The engine itself is at <a href="${REPO}">${REPO}</a>.</p>`; return; }
  const sel = $("#caseselect");
  sel.innerHTML = cases.map((c) => `<option value="${esc(c.id)}">${esc(c.id)} — ${esc(c.title)}</option>`).join("");
  sel.addEventListener("change", () => loadCase(sel.value));
  root.addEventListener("input", (e) => {
    const el = e.target; if (!el.matches("input[data-doc]")) return;
    applyEdit(bundle, el.dataset.doc, el.dataset.line === undefined ? null : Number(el.dataset.line), el.dataset.key, el.value);
    run();
  });
  root.addEventListener("click", (e) => {
    const del = e.target.closest("[data-del]"), add = e.target.closest("[data-add]");
    if (del) { const [doc, i] = del.dataset.del.split(":"); bundle[doc].lines.splice(Number(i), 1); render(); }
    if (add) { bundle[add.dataset.add].lines ??= []; bundle[add.dataset.add].lines.push({}); render(); }
  });
  $("#reset").addEventListener("click", () => loadCase(current.id));
  document.addEventListener("dalteno:lang", () => { if (bundle) render(); });
  loadCase("C00_clean");
  const params = new URLSearchParams(location.search);
  if (params.get("case") && cases.some((c) => c.id === params.get("case"))) { sel.value = params.get("case"); loadCase(sel.value); }
}
init();
